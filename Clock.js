var r1 = 250;
var r2 = 300;
var r3 = 325;
var r_sec = 190;
var r_min = 150;
var r_hour = 100;
var p,q;
var image = new Image();
image.src = "mickeymouse.gif";

function DrawAnalogClock(px, py, hour, minute, second) {
    var x, y;
    ctx.strokeStyle = "black";
    ctx.beginPath();
    ctx.lineWidth = 10;
    ctx.arc(px, py, r3, 0, 2 * Math.PI);
    ctx.stroke();
    
    for (p = 60, q = 1; q <= 12; p-=30, q++) {
      ctx.font = "60px Arial";
      ctx.fillStyle = "black";
      x = r1*(Math.cos(p*Math.PI/180));
      y = r1*(Math.sin(p*Math.PI/180));
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.fillText(q, px+x, py-y);
      x = r2*(Math.cos(p*Math.PI/180));
      y = r2*(Math.sin(p*Math.PI/180));
      ctx.beginPath();
      ctx.arc(px+x, py-y, 5, 0, 2 * Math.PI);
      ctx.fill();
    }
    
    ctx.drawImage(image, 1050, 230, 200, 200);

    DrawHand(px, py, minute, r_min, 10, false, 0, false);
    DrawHand(px, py, hour, r_hour, 10, true, minute, false);
    DrawHand(px, py, second, r_sec, 5, false, 0, true);
}

function DrawHand(px, py, t, r, width, isHour, min, isSecond) {
  var angle = 0;
  var x, y;
  
  if (isHour) {
    t = t % 12;
  }
  
  angle=(isHour) ? (-30*t+90)-min/2 : -6*t+90;
  
  ctx.globalAlpha = 0.5;
  ctx.beginPath();
  ctx.moveTo(px, py);
  x = r*(Math.cos(angle*Math.PI/180));
  y = r*(Math.sin(angle*Math.PI/180));
  ctx.lineTo(px+x, py-y);
  ctx.lineWidth = width;
  
  ctx.strokeStyle=(isSecond) ? ("red") : ("black");

  ctx.stroke();
  
  ctx.fillStyle="red";
  ctx.beginPath();
  ctx.arc(px, py, 5, 0, 2 * Math.PI);
  ctx.fill();
}

function DrawDigitalClock(px, py, h, m, s, ms) {
  ctx.fillStyle="black";
  ctx.fillRect(px,py,700, 300);
  
  h2 = h % 12;
  if (!h2) {
    h2 = 12;
  }

  var x = px+155;
  var y = py+50;
  var str = ((m < 10) ? "0" : "") + m;
  str = str + ((ms<500) ? ":" : " ");
  str = str + ((s<10) ? "0" : "") + s;
  str = h2 + ":" + str;
  
loop:
  for (var k=0; k<str.length; k++) {
    var character = str.charAt(k);
    var index = parseInt(character);
    
    if (character.includes(":")) {
      index = 10;
    } else if (character.includes(" ")) {
      x+=50;
      continue loop;
    }

    
    for (var i=0; i<clockNumbers[index].length; i++) {
      for (var j=0; j<clockNumbers[index][i].length; j++) {
          if (clockNumbers[index][i][j]){
              ctx.fillStyle="white";
              ctx.fillRect(x+j*2, y+i*2, 2, 2);
          }
      }
    }

    x+=50;
  }
  
  ctx.font = "60px Arial";
  
  str = (h>=12) ? "PM" : "AM";
  ctx.fillText(str, px+630, py+200);

  ctx.fillText(ms, px+630, py+115);
}

